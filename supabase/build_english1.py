"""Builds supabase/seed_english1.sql from content/e1_*.py. Run: python3 supabase/build_english1.py"""
import json, random, re, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'content'))
from e1_units1 import UNIT1, UNIT2
from e1_units2 import UNIT3, UNIT4
from e1_units3 import UNIT5, UNIT6, FINAL

UNITS = [UNIT1, UNIT2, UNIT3, UNIT4, UNIT5, UNIT6]
PRESENTER = "Dr. Alex L. Jenkins Sr."
FOCUS = ("English 1 builds the habits of a strong reader, thinker and writer. Students read fiction, poetry and informational "
         "texts, including Scripture in the King James Version, learn to build and judge arguments, and practice the full writing "
         "process from plan to published copy. The course aligns to the Florida B.E.S.T. ELA standards for grade 9 and ends with "
         "a final argumentative essay of 500 words or more. Excellence, Faith, Purpose.")

rng = random.Random(1001310)
def shuffle_q(q):
    text, opts, ci, ex = q
    order = list(range(len(opts))); rng.shuffle(order)
    return text, [opts[i] for i in order], order.index(ci), ex

def quiz(title, qs):
    qs = [shuffle_q(q) for q in qs]
    return dict(title=title,
        content={"questions": [{"q": q[0], "options": q[1]} for q in qs]},
        answers=[q[2] for q in qs], explains=[q[3] for q in qs])

topics, assessments, discussions, quizzes = [], [], [], []
for u in UNITS:
    for t in u['topics']:
        body = t['body'].strip() + "\n\nFlorida standards: " + t['std'] + "."
        topics.append(dict(title=t['t'], content=dict(body=body, video="", presenter=PRESENTER, standards=t['std'], script=t['script'].strip())))
    assessments.append(dict(title=u['assess']['t'], content=dict(prompt=u['assess']['prompt'], rubric=u['assess']['rubric'])))
    discussions.append(dict(title=u['disc']['t'], content=dict(prompt=u['disc']['prompt'])))
    n = u['title'].split(':')[0].replace('Unit ', '')
    for t in u['topics']:
        quizzes.append(quiz("Check " + t['t'].split(' ')[0] + ": " + t['t'].split(' ', 1)[1], t['quiz']))
    quizzes.append(quiz(u['title'].replace('Unit ', 'Unit Quiz ', 1), u['unit_quiz']))
assessments.append(dict(title=FINAL['assess']['t'], content=dict(prompt=FINAL['assess']['prompt'], rubric=FINAL['assess']['rubric'])))
quizzes.append(quiz("Final Exam: English 1", FINAL['quiz']))

# prose check: no hyphens or dashes anywhere in student facing text
bad = []
def scan(label, s):
    if re.search(r'[-‐-―]', s): bad.append(label)
scan('focus', FOCUS)
for grp in (topics, assessments, discussions):
    for it in grp:
        scan(it['title'], it['title'])
        for k, v in it['content'].items():
            if isinstance(v, str): scan(it['title'] + ':' + k, v)
for it in quizzes:
    scan(it['title'], it['title'])
    for q in it['content']['questions']:
        scan(it['title'] + ' q', q['q'] + ' '.join(q['options']))
    scan(it['title'] + ' ex', ' '.join(it['explains']))
if bad:
    print("HYPHENS FOUND IN:", bad); sys.exit(1)

def lit(s): return "$j$" + s + "$j$"
out = ["-- English 1 seed. Safe to run once; it does nothing if the course already has items.", "-- Generated by supabase/build_english1.py", ""]
out.append("insert into public.courses (slug, title, subject, credits, focus)\nvalues ('english-1', 'English 1', 'English Language Arts', 1.0, " + lit(FOCUS) + ")\non conflict (slug) do nothing;\n")
out.append("do $seed$\ndeclare cid uuid;\nbegin\n  select id into cid from public.courses where slug = 'english-1';\n  if exists (select 1 from public.course_items where course_id = cid) then\n    raise notice 'english-1 already has items; nothing inserted';\n    return;\n  end if;")
def ins(kind, items):
    for i, it in enumerate(items, 1):
        out.append(f"  insert into public.course_items (course_id, kind, position, title, content) values (cid, '{kind}', {i}, {lit(it['title'])}, {lit(json.dumps(it['content'], ensure_ascii=False))}::jsonb);")
ins('topic', topics); ins('assessment', assessments); ins('discussion', discussions); ins('quiz', quizzes)
for it in quizzes:
    ans = "{" + ",".join(map(str, it['answers'])) + "}"
    ex = "array[" + ",".join(lit(e) for e in it['explains']) + "]"
    out.append(f"  insert into public.quiz_keys (item_id, answers, explains) select id, '{ans}'::int[], {ex} from public.course_items where course_id = cid and kind = 'quiz' and title = {lit(it['title'])};")
out.append("end\n$seed$;")
path = os.path.join(os.path.dirname(__file__), 'seed_english1.sql')
open(path, 'w', encoding='utf-8').write("\n".join(out) + "\n")
print("topics", len(topics), "assessments", len(assessments), "discussions", len(discussions), "quizzes", len(quizzes),
      "questions", sum(len(q['answers']) for q in quizzes))
